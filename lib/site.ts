/**
 * The site's origin, for example https://kunanonj.com, with no trailing slash
 * (resolvePublicSiteUrl strips it). Fail-closed: never fronk.example.com in
 * production.
 */
export const SITE_ORIGIN = resolvePublicSiteUrl();

/** The origin without its scheme, as the share cards print it. */
export const SITE_DOMAIN = SITE_ORIGIN.replace(/^https?:\/\//, "");

/** A site path with its leading slash: `sitePath("about")` is "/about". */
export function sitePath(path: string): string {
  return path.startsWith("/") ? path : `/${path}`;
}

/** An absolute URL on the site: `siteUrl("/about")`. */
export function siteUrl(path: string): string {
  return `${SITE_ORIGIN}${sitePath(path)}`;
}

