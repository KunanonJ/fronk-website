#!/usr/bin/env node
/**
 * Open-source snapshot sync: the owner's open-source projects on GitHub ->
 * `lib/content/openSource.generated.json` (committed).
 *
 *   pnpm oss:sync            # read GitHub; write the snapshot if a fact changed
 *   pnpm oss:sync --check    # exit 1 if GitHub's facts differ from the snapshot
 *
 * Why a snapshot: /open-source, its Markdown and the Home strip are built
 * from this file only, so neither a build nor a page view calls GitHub (the
 * Worker has no token, and GitHub allows 60 unauthenticated requests an
 * hour). The owner re-runs it after a release, or when the numbers should be
 * fresh. `--check` reads GitHub too, so it is a local tool, not a CI gate:
 * stars move on their own.
 *
 * Reads, per repository (three requests): the repository, its latest release
 * (none is fine) and the newest commit on its default branch, whose date is
 * "Updated" (`pushed_at` also moves for pushes to other branches).
 * `GITHUB_TOKEN` is used when set.
 *
 * `homepage` is GitHub's field as the owner set it, and nothing here checks
 * that it loads: before the site links one (lib/content/openSource.ts),
 * open it. OpenFinance's did not resolve on 21-11-26, so the site links no
 * app for it.
 *
 * Output is stable: projects in REPOS order, keys in a fixed order, and no
 * timestamp but the facts themselves and `syncedOn`, the UTC day they were
 * read. A run that finds the same facts leaves the file as it is, so
 * `syncedOn` moves only with a change.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/** The projects the site lists, in its order (owner decision, 21-11-26). */
export const REPOS = [
  "KunanonJ/superstacks",
  "KunanonJ/thai-accounting-tax-law",
  "KunanonJ/OpenFinance",
];
export const OUTPUT_PATH = "lib/content/openSource.generated.json";

/**
 * Pure: one repository's GitHub answers -> its facts. Throws for a
 * repository the site must not list: private, a fork, archived, or with no
 * license GitHub can name.
 *
 * @param {{ repo: Record<string, any>, release: Record<string, any> | null, head: Record<string, any> | null }} raw
 */
export function projectFacts({ repo, release, head }) {
  const name = repo.full_name;
  if (repo.private) throw new Error(`${name} is private`);
  if (repo.fork) throw new Error(`${name} is a fork`);
  if (repo.archived) throw new Error(`${name} is archived`);
  const license = repo.license?.spdx_id;
  if (typeof license !== "string" || license === "NOASSERTION") {
    throw new Error(`${name} has no license GitHub can name`);
  }
  const committedAt = head?.commit?.committer?.date;
  if (typeof committedAt !== "string") {
    throw new Error(`${name} has no commit on ${repo.default_branch}`);
  }
  return {
    repo: name,
    url: repo.html_url,
    homepage: repo.homepage || null,
    license,
    language: repo.language ?? null,
    stars: repo.stargazers_count,
    forks: repo.forks_count,
    defaultBranch: repo.default_branch,
    lastCommitAt: committedAt,
    release: release
      ? {
          tag: release.tag_name,
          name: release.name || release.tag_name,
          publishedAt: release.published_at,
          url: release.html_url,
        }
      : null,
  };
}

/**
 * Pure: every repository's answers -> the committed snapshot, in REPOS
 * order. `syncedOn` is the UTC day the answers were read (YYYY-MM-DD).
 *
 * @param {{ repo: Record<string, any>, release: Record<string, any> | null, head: Record<string, any> | null }[]} raws
 * @param {string} syncedOn
 */
export function buildSnapshot(raws, syncedOn) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(syncedOn)) {
    throw new Error(`syncedOn must be a UTC day (YYYY-MM-DD), not ${syncedOn}`);
  }
  const byName = new Map(raws.map((raw) => [raw.repo.full_name, raw]));
  return {
    $comment:
      "Generated by scripts/sync-open-source.mjs. Do not edit; run `pnpm oss:sync`.",
    syncedOn,
    projects: REPOS.map((name) => {
      const raw = byName.get(name);
      if (!raw) throw new Error(`GitHub sent nothing for ${name}`);
      return projectFacts(raw);
    }),
  };
}

/** The facts without the day they were read: what a re-run and --check compare. */
export function factsOf(snapshot) {
  const { syncedOn: _day, ...facts } = snapshot;
  return JSON.stringify(facts);
}

/** One line per fact that moved, e.g. `KunanonJ/superstacks stars: 5 -> 6`. */
export function describeChanges(current, next) {
  const lines = [];
  const before = new Map((current?.projects ?? []).map((p) => [p.repo, p]));
  for (const project of next.projects) {
    const old = before.get(project.repo);
    if (!old) {
      lines.push(`${project.repo}: new`);
      continue;
    }
    for (const key of Object.keys(project)) {
      const a = JSON.stringify(old[key]);
      const b = JSON.stringify(project[key]);
      if (a !== b) lines.push(`${project.repo} ${key}: ${a} -> ${b}`);
    }
  }
  for (const repo of before.keys()) {
    if (!next.projects.some((p) => p.repo === repo))
      lines.push(`${repo}: gone`);
  }
  return lines;
}

/** Deterministic serialisation: 2-space JSON plus a trailing newline. */
export function serializeSnapshot(snapshot) {
  return `${JSON.stringify(snapshot, null, 2)}\n`;
}

/* ─── GitHub I/O (only used when run as a script) ──────────────────────────── */

async function getJson(url, { optional = false } = {}) {
  const headers = {
    Accept: "application/vnd.github+json",
    "User-Agent": "kunanonj-oss-sync",
    "X-GitHub-Api-Version": "2022-11-28",
  };
  const token = process.env.GITHUB_TOKEN?.trim();
  if (token) headers.Authorization = `Bearer ${token}`;
  const res = await fetch(url, { headers });
  if (optional && res.status === 404) return null;
  if (!res.ok) {
    throw new Error(
      `GET ${url} -> ${res.status} ${res.statusText}${token ? "" : " (set GITHUB_TOKEN to raise the rate limit)"}`,
    );
  }
  return res.json();
}

/** The three answers for one repository. */
export async function fetchRaw(name) {
  const api = `https://api.github.com/repos/${name}`;
  const [repo, release] = await Promise.all([
    getJson(api),
    getJson(`${api}/releases/latest`, { optional: true }),
  ]);
  const commits = await getJson(
    `${api}/commits?sha=${encodeURIComponent(repo.default_branch)}&per_page=1`,
  );
  return { repo, release, head: commits[0] ?? null };
}

async function main() {
  const args = process.argv.slice(2);
  for (const arg of args) {
    if (arg !== "--check") throw new Error(`Unknown argument: ${arg}`);
  }
  const check = args.includes("--check");
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const outFile = path.join(root, OUTPUT_PATH);
  const today = new Date().toISOString().slice(0, 10);

  const next = buildSnapshot(await Promise.all(REPOS.map(fetchRaw)), today);
  const current = fs.existsSync(outFile)
    ? JSON.parse(fs.readFileSync(outFile, "utf8"))
    : null;
  const same = current !== null && factsOf(current) === factsOf(next);

  if (check) {
    if (!same) {
      console.error(
        [
          `[oss] ${OUTPUT_PATH} is out of date. Run pnpm oss:sync.`,
          ...describeChanges(current, next).map((line) => `  ${line}`),
        ].join("\n"),
      );
      process.exit(1);
    }
    console.log(
      `[oss] ${OUTPUT_PATH} matches GitHub (${next.projects.length} projects, as of ${current.syncedOn}).`,
    );
    return;
  }
  if (same) {
    console.log(
      `[oss] No changes: ${next.projects.length} projects, as of ${current.syncedOn}.`,
    );
    return;
  }
  fs.writeFileSync(outFile, serializeSnapshot(next));
  console.log(
    [
      `[oss] Wrote ${OUTPUT_PATH} (${next.projects.length} projects, as of ${today}).`,
      ...describeChanges(current, next).map((line) => `  ${line}`),
    ].join("\n"),
  );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  main().catch((error) => {
    console.error(`[oss] ${error instanceof Error ? error.message : error}`);
    process.exit(1);
  });
}
